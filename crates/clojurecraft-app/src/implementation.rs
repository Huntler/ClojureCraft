//! The right column: the current implementation and its result, step, and source views.

use clojurecraft_domain::FunctionDocument;
use egui::{Id, RichText, Ui};

use crate::edn_view;
use crate::theme;

#[derive(Clone, Copy, Debug, Default, PartialEq, Eq)]
pub enum Tab {
    #[default]
    Implementation,
    Result,
    Steps,
    Sources,
}

impl Tab {
    const ALL: [Self; 4] = [Self::Implementation, Self::Result, Self::Steps, Self::Sources];

    fn label(self) -> &'static str {
        match self {
            Self::Implementation => "Implementation",
            Self::Result => "Result",
            Self::Steps => "Steps",
            Self::Sources => "Sources",
        }
    }
}

pub fn show(ui: &mut Ui, tab: &mut Tab, doc: Option<&FunctionDocument>) {
    ui.add_space(8.0);
    ui.horizontal_wrapped(|ui| {
        ui.spacing_mut().button_padding.x = 6.0;
        ui.spacing_mut().item_spacing.x = 2.0;
        for t in Tab::ALL {
            if ui.selectable_label(*tab == t, t.label()).clicked() {
                *tab = t;
            }
        }
    });
    ui.separator();
    let Some(doc) = doc else {
        empty(ui, "Open or create a function to see its implementation.");
        return;
    };
    egui::ScrollArea::vertical()
        .id_salt("right-column")
        .auto_shrink([false, false])
        .show(ui, |ui| match tab {
            Tab::Implementation => implementation(ui, doc),
            Tab::Result => result(ui, doc),
            Tab::Steps => steps(ui, doc),
            Tab::Sources => sources(ui, doc),
        });
}

fn empty(ui: &mut Ui, text: &str) {
    ui.add_space(12.0);
    ui.label(RichText::new(text).color(theme::MUTED));
}

fn implementation(ui: &mut Ui, doc: &FunctionDocument) {
    let Some(implementation) = &doc.implementation else {
        empty(
            ui,
            "No implementation yet. Implementations are generated from the specification by the \
             local model and checked against your examples.",
        );
        return;
    };
    let origin = match &implementation.generation {
        Some(g) if !implementation.is_manually_edited() => format!(
            "Generated by {} ({}) with llama.cpp {} on {}",
            g.model.display_name, g.model.quantization, g.runtime.llama_cpp_release, g.runtime.backend
        ),
        Some(_) => "Generated, then edited by hand".to_owned(),
        None => "Written by hand".to_owned(),
    };
    ui.label(RichText::new(origin).small().color(theme::MUTED));
    ui.add_space(4.0);
    egui::Frame::new()
        .fill(theme::SUNKEN)
        .stroke(theme::hairline())
        .corner_radius(theme::RADIUS)
        .inner_margin(6.0)
        .show(ui, |ui| {
            edn_view::code_view(ui, Id::unique(("implementation", doc.id)), &implementation.source);
        });
}

fn result(ui: &mut Ui, doc: &FunctionDocument) {
    if doc.implementation.is_none() {
        empty(ui, "Nothing to validate yet.");
    } else {
        empty(ui, "This implementation has not been validated.");
    }
}

fn steps(ui: &mut Ui, doc: &FunctionDocument) {
    if doc.steps.is_empty() {
        empty(ui, "This function has no transformation steps.");
        return;
    }
    for (i, step) in doc.steps.iter().enumerate() {
        ui.horizontal_wrapped(|ui| {
            ui.label(RichText::new(format!("{}.", i + 1)).color(theme::MUTED));
            let text = step.text.trim();
            ui.label(if text.is_empty() { "(empty step)" } else { text });
        });
    }
    ui.add_space(8.0);
    ui.label(
        RichText::new("Intermediate values appear here once the implementation has been run.")
            .small()
            .color(theme::MUTED),
    );
}

fn sources(ui: &mut Ui, doc: &FunctionDocument) {
    let docs = doc
        .implementation
        .as_ref()
        .and_then(|i| i.generation.as_ref())
        .map(|g| g.documentation.as_slice())
        .unwrap_or_default();
    if docs.is_empty() {
        empty(ui, "No documentation was used for this implementation.");
        return;
    }
    for d in docs {
        ui.label(RichText::new(&d.title).strong());
        let symbol = match (&d.namespace, &d.symbol) {
            (Some(ns), Some(sym)) => format!("{ns}/{sym} · "),
            (None, Some(sym)) => format!("{sym} · "),
            _ => String::new(),
        };
        ui.label(
            RichText::new(format!(
                "{symbol}Clojure {} · {}",
                d.clojure_version, d.source_url
            ))
            .small()
            .color(theme::MUTED),
        );
        ui.add_space(6.0);
    }
}
